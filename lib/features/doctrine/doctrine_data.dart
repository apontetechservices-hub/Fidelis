/// Catechetical reference lists — the classic 'Summary of Catholic Doctrine'
/// enumerations in standard traditional (Baltimore-style) forms.
/// Interface language swaps English/Spanish (novenas pattern); no Latin
/// toggle — reference content, not prayer text.
class DoctrineTopic {
  final String id;
  final String title;
  final String titleEs;
  final IconData icon;
  final List<String> items;
  final List<String> itemsEs;

  const DoctrineTopic({
    required this.id,
    required this.title,
    required this.titleEs,
    required this.icon,
    required this.items,
    required this.itemsEs,
  });

  String titleFor(String lang) => lang == 'es' ? titleEs : title;
  List<String> itemsFor(String lang) => lang == 'es' ? itemsEs : items;
}

